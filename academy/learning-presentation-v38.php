/** Remove only outline numbering. Quantities, percentages and teaching text remain intact. */
function academy_heading_display(string $heading): string {
    return preg_replace('/^\s*\d{1,3}(?:\.\d{1,3})*[.)]\s+/u','',trim($heading))??$heading;
}

