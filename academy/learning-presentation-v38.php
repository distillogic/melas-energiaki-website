function academy_quiz_presentation(string $lesson,int $i,array $question): array {
    $text=trim((string)$question[0]);$context='';$ask=$text;
    // Separate the scenario from its actual question. Decimal points are not sentence boundaries.
    if(preg_match('/[;?;]$/u',$text)){
        $cut=mb_strrpos($text,'. ');
        if($cut!==false){$context=mb_substr($text,0,$cut+1);$ask=mb_substr($text,$cut+2);}
    }else{$context=$text;$original=academy_lesson($lesson)['quiz'][$i][0]??null;$ask=$original===$text?academy_quiz_ask($lesson,$i):'Ποια επιλογή απαντά σωστά στο περιστατικό;';}
    return ['context'=>academy_quiz_plain($context),'ask'=>academy_quiz_plain($ask),'options'=>array_map('academy_quiz_plain',$question[1]),'why'=>academy_quiz_plain($question[3])];
}
